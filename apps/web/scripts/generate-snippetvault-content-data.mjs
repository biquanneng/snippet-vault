import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { renderToStaticMarkup } from "react-dom/server";
import { compileMDX } from "next-mdx-remote/rsc";
import remarkGfm from "remark-gfm";

const projectRoot = process.cwd();
const guidesDirectory = path.join(
  projectRoot,
  "content",
  "snippetvault",
  "guides",
);
const outputPath = path.join(
  projectRoot,
  "lib",
  "snippetvault",
  "content-data.ts",
);
const requiredFields = [
  "title",
  "description",
  "category",
  "primaryKeyword",
  "searchIntent",
  "publishedAt",
  "updatedAt",
  "readingTime",
  "order",
];

function unquote(value) {
  const trimmed = value.trim();

  if (
    (trimmed.startsWith("\"") && trimmed.endsWith("\"")) ||
    (trimmed.startsWith("'") && trimmed.endsWith("'"))
  ) {
    return trimmed.slice(1, -1);
  }

  return trimmed;
}

function parseFrontmatter(filename, source) {
  const lines = source.split(/\r?\n/);

  if (lines[0]?.trim() !== "---") {
    throw new Error(`${filename} must start with frontmatter.`);
  }

  const closingIndex = lines.findIndex(
    (line, index) => index > 0 && line.trim() === "---",
  );

  if (closingIndex === -1) {
    throw new Error(`${filename} has unclosed frontmatter.`);
  }

  const metadata = {};

  for (const line of lines.slice(1, closingIndex)) {
    const separatorIndex = line.indexOf(":");

    if (separatorIndex === -1) {
      continue;
    }

    const key = line.slice(0, separatorIndex).trim();
    const value = unquote(line.slice(separatorIndex + 1));
    metadata[key] = key === "order" ? Number(value) : value;
  }

  for (const field of requiredFields) {
    if (
      metadata[field] === undefined ||
      metadata[field] === "" ||
      (field === "order" && !Number.isFinite(metadata[field]))
    ) {
      throw new Error(`${filename} is missing valid frontmatter "${field}".`);
    }
  }

  return metadata;
}

const guideFiles = readdirSync(guidesDirectory)
  .filter((filename) => filename.endsWith(".md"))
  .sort();
const html = {};
const metadata = {};

for (const filename of guideFiles) {
  const slug = filename.replace(/\.md$/, "");
  const source = readFileSync(path.join(guidesDirectory, filename), "utf8");
  metadata[slug] = parseFrontmatter(filename, source);
  const result = await compileMDX({
    source,
    options: {
      parseFrontmatter: true,
      mdxOptions: {
        remarkPlugins: [remarkGfm],
      },
    },
  });
  html[slug] = renderToStaticMarkup(result.content);
}

const output = `// SPDX-License-Identifier: MPL-2.0
// This file is generated by scripts/generate-snippetvault-content-data.mjs.
// Do not edit it directly; edit content/snippetvault/guides/*.md instead.

export const snippetVaultGuideHtml = ${JSON.stringify(html, null, 2)} as const;

export const snippetVaultGuideMetadata = ${JSON.stringify(metadata, null, 2)} as const;
`;

mkdirSync(path.dirname(outputPath), { recursive: true });
writeFileSync(outputPath, output);
